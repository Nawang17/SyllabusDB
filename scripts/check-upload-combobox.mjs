import { chromium, expect } from '@playwright/test'

// Read-only smoke check: edits local form fields without submitting or signing in.
const browser = await chromium.launch()
try {
  const page = await browser.newPage({ viewport:{ width:390, height:844 } })
  await page.goto(new URL('/uploadSyllabus', process.argv[2] || 'http://127.0.0.1:5173').href)
  const college = page.getByRole('combobox', { name:'College', exact:false })
  const course = page.getByRole('combobox', { name:'Course code', exact:false })
  await expect(college).toBeEnabled({ timeout:20_000 })
  await expect(college).toHaveCount(1)
  await expect(page.getByLabel('Search College', { exact:true })).toHaveCount(0)
  await college.fill('hunter')
  await expect(page.getByRole('option', { name:'Hunter College', exact:true })).toBeVisible()
  await college.press('ArrowDown')
  await college.press('Enter')
  await expect(college).toHaveValue('Hunter College')
  await expect(course).toBeEnabled()
  await expect(page.getByText('Loading course suggestions...', { exact:true })).not.toBeVisible({ timeout:20_000 })
  await course.fill('csci260')
  await expect(page.getByRole('option', { name:/^CSCI 260\b/ }).first()).toBeVisible()
  await course.press('ArrowDown')
  await course.press('Enter')
  await expect(course).toHaveValue('CSCI 260')
  await expect(page.locator('#upload-course-title')).not.toHaveValue('')
  await course.fill('zzzt999')
  await course.press('Tab')
  await expect(course).toHaveValue('ZZZT 999')
  await expect(page.locator('#upload-course-title')).toBeEditable()
  await college.fill('No such college 12345')
  await expect(page.getByText('No college found', { exact:true })).toBeVisible()
  await expect(course).toBeDisabled()
  expect(await college.evaluate(input => input.validity.valid)).toBeFalsy()
  console.log('Single-field college filtering, keyboard selection, course suggestions, custom course codes, and invalid college clearing passed. No form was submitted.')
} finally { await browser.close() }
