test('desktop header stays simple while mobile controls move into the sidebar', async ({ page }, testInfo) => {
  for (const width of [320,390,1280]) {
    await page.setViewportSize({ width, height:844 })
    await page.goto('/aboutpage')
    const header = page.locator('.site-header')
    await expect(header.getByRole('link', { name:'SyllabusDB', exact:true })).toBeVisible()
    const mobile = width <= 768
    const upload = header.getByRole('link', { name:'Upload syllabus', exact:true })
    if (mobile) {
      await expect(upload).not.toBeVisible()
      await expect(header.getByRole('button', { name:'Color theme', exact:true })).not.toBeVisible()
      await page.getByRole('button', { name:'Open navigation menu' }).click()
      await expect(page.getByRole('dialog', { name:'Menu', exact:true })).toBeVisible()
    } else {
      await expect(upload).toBeVisible()
      await expect(header.getByRole('button', { name:'Color theme', exact:true })).toBeVisible()
      await expect(page.getByRole('button', { name:'Open navigation menu' })).not.toBeVisible()
    }
    const scope = mobile ? page.getByRole('dialog', { name:'Menu', exact:true }) : header
    const signin = scope.getByRole('link', { name:'Sign in', exact:true })
    await expect(signin).toBeVisible()
    await expect(signin).toHaveAttribute('href','/signin')
    await expect(scope.getByRole('button', { name:'Account menu', exact:true })).toHaveCount(0)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
    if (mobile) {
      await chooseTheme(page, 'dark')
      await expect(page.locator('html')).toHaveClass('dark')
      await expect(scope.getByRole('link', { name:'Upload syllabus', exact:true })).toBeVisible()
      if (width === 390) await page.screenshot({ path:testInfo.outputPath('mobile-sidebar.png'), fullPage:false })
      await scope.getByRole('button', { name:'Close navigation menu' }).click()
      await expect(page.getByRole('button', { name:'Open navigation menu' })).toBeFocused()
    }
    if (width !== 320) await page.screenshot({ path:testInfo.outputPath(`simple-header-${width}.png`), fullPage:false })
  }
  await page.setViewportSize({ width:390, height:844 })
  await page.getByRole('button', { name:'Open navigation menu' }).click()
  await page.getByRole('dialog', { name:'Menu', exact:true }).getByRole('link', { name:'Browse colleges', exact:true }).click()
  await expect(page).toHaveURL(/\/colleges$/)
  await expect(page.getByRole('dialog', { name:'Menu', exact:true })).not.toBeVisible()
  await page.getByRole('button', { name:'Open navigation menu' }).click()
  await page.setViewportSize({ width:1280, height:844 })
  await expect(page.getByRole('dialog', { name:'Menu', exact:true })).not.toBeVisible()
  await expect(page.getByRole('button', { name:'Color theme', exact:true })).toHaveAttribute('title','Color theme: dark')
})

