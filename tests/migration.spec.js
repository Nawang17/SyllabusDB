import { test, expect } from '@playwright/test'
const course = '/college/test-college/subject/CS-GY/course/CS-GY%209215'
async function chooseTheme(page, theme) {
  await page.getByRole('button', { name:'Color theme', exact:true }).click()
  await page.getByRole('menuitemradio', { name:theme[0].toUpperCase() + theme.slice(1), exact:true }).click()
}
test.beforeEach(async ({ page }) => {
  // Prevent fixture runs from making requests to real Firebase or the separate backend.
  await page.route(/https:\/\/(?!127\.0\.0\.1|localhost)/, route => route.abort())
})
test('homepage remains interactive when the animated syllabus counter mounts', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error' && /Element type is invalid|Minified React error/.test(message.text())) errors.push(message.text()) })
  await page.goto('/')
  await expect(page.getByLabel('Color theme')).toBeEnabled()
  await expect(page.getByRole('heading', { name:'Know your class before you enroll.' })).toBeVisible()
  // With external requests blocked, Firestore's initial offline stats snapshot is zero.
  // This still mounts the animation, which the static SSR checks cannot exercise.
  await expect(page.locator('.hero-syllabi-count')).toBeVisible({ timeout:15_000 })
  await expect(page.locator('.hero-syllabi-count strong')).toHaveText('0')
  await expect(page.getByRole('heading', { name:'Know your class before you enroll.' })).toBeVisible()
  expect(errors).toEqual([])
})
test('public routes hydrate, navigate, refresh and retain history', async ({ page }) => {
  const errors = []
  page.on('pageerror',error => errors.push(error.message))
  page.on('console',message => { if (/hydration|did not match|server rendered/i.test(message.text())) errors.push(message.text()) })
  await page.goto('/colleges')
  await expect(page.getByLabel('Color theme')).toBeEnabled()
  await expect(page.getByRole('searchbox')).toBeEnabled()
  await page.getByRole('link',{ name: /Test College/ }).click()
  await expect(page.getByRole('heading',{ name: 'Test College' })).toBeVisible()
  await page.getByRole('link',{ name: /CS-GY 9215 Distributed Systems/ }).click()
  await page.getByRole('link',{ name: /Fall.*Test Professor/ }).click()
  await expect(page.getByRole('heading',{ name: /CS-GY 9215.*Distributed Systems/ })).toBeVisible()
  await expect(page.locator('iframe')).toHaveAttribute('src','https://example.com/test.pdf')
  await page.reload()
  await expect(page.getByRole('heading',{ name: /CS-GY 9215.*Distributed Systems/ })).toBeVisible()
  // The heading is already in SSR HTML; wait for the interactive boundary before history actions.
  await expect(page.getByRole('button',{ name:'Mark syllabus helpful' })).toBeEnabled()
  await page.goBack()
  await expect(page.getByRole('heading',{ name: 'Published syllabi' })).toBeVisible()
  await page.goForward()
  await expect(page.getByRole('heading',{ name: /CS-GY 9215.*Distributed Systems/ })).toBeVisible()
  expect(errors).toEqual([])
})
test('light, dark and system themes persist and follow system changes', async ({ page }) => {
  await page.emulateMedia({ colorScheme:'dark' })
  await page.goto('/aboutpage')
  await expect(page.locator('html')).toHaveClass('dark')
  await chooseTheme(page, 'light')
  await expect(page.locator('html')).not.toHaveClass('dark')
  await expect(page.locator('.theme-toggle .theme-sun')).toBeVisible()
  await page.reload()
  await expect(page.getByLabel('Color theme')).toHaveAttribute('title', 'Color theme: light')
  await expect(page.locator('html')).not.toHaveClass('dark')
  await chooseTheme(page, 'dark')
  await expect(page.locator('.theme-toggle .theme-moon')).toBeVisible()
  await page.reload()
  await expect(page.locator('html')).toHaveClass('dark')
  await chooseTheme(page, 'system')
  await page.emulateMedia({ colorScheme:'light' })
  await expect(page.locator('html')).not.toHaveClass('dark')
  await page.emulateMedia({ colorScheme:'dark' })
  await expect(page.locator('html')).toHaveClass('dark')
})

test('college courses support popularity, letter filters, search and direct navigation', async ({ page }) => {
  await page.setViewportSize({ width:390, height:844 })
  await page.goto('/college/test-college')
  await expect(page.locator('main').getByRole('navigation', { name:'Breadcrumb' })).toHaveCount(0)
  await page.setViewportSize({ width:320, height:844 })
  const scrollLeft = page.getByRole('button', { name:'Scroll course filters left' })
  const scrollRight = page.getByRole('button', { name:'Scroll course filters right' })
  await expect(scrollLeft).toHaveCount(0)
  await expect(scrollRight).toBeVisible()
  await scrollRight.click()
  await expect(scrollLeft).toBeEnabled()
  await expect(scrollRight).toHaveCount(0)
  await scrollLeft.click()
  await expect(scrollLeft).toHaveCount(0)
  await page.setViewportSize({ width:390, height:844 })
  const list = page.getByRole('list', { name:'College courses' })
  await expect(list.getByRole('heading')).toHaveText(['ART 101','ACCT 101','CS-GY 9215','2D 101'])
  await page.getByRole('button', { name:'Courses starting with A', exact:true }).click()
  await expect(list.getByRole('heading')).toHaveText(['ACCT 101','ART 101'])
  await page.getByRole('searchbox').fill('painting')
  await expect(list.getByRole('heading')).toHaveText(['ART 101'])
  await page.getByRole('searchbox').fill('missing course')
  await expect(page.getByText('No courses match these filters.')).toBeVisible()
  await page.getByRole('button', { name:'Clear filters' }).click()
  await page.getByRole('button', { name:'Other course codes' }).click()
  await expect(list.getByRole('heading')).toHaveText(['2D 101'])
  await expect(page.getByRole('button', { name:'Courses starting with Z', exact:true })).toHaveCount(0)
  await expect(page.getByRole('group', { name:'Course filters' }).getByRole('button')).toHaveText(['Popular','A','C','#'])
  await page.getByRole('button', { name:'Popular', exact:true }).click()
  await expect(list.getByRole('heading').first()).toHaveText('ART 101')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.getByRole('link', { name:/CS-GY 9215 Distributed Systems/ }).click()
  await expect(page).toHaveURL(/\/college\/test-college\/subject\/CS-GY\/course\/CS-GY%209215$/)
  await expect(page.getByRole('heading', { name:'Published syllabi' })).toBeVisible()
})

